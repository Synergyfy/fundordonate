import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Post,
  Query,
  Req,
  Res,
  UseGuards,
} from "@nestjs/common";
import {
  ApiBearerAuth,
  ApiOperation,
  ApiQuery,
  ApiTags,
} from "@nestjs/swagger";
import type { Request, Response } from "express";
import { SsoService } from "./sso.service";
import { SsoCallbackDto } from "./dto/sso-callback.dto";
import { SsoDirectLoginDto } from "./dto/sso-direct-login.dto";
import { JwtAuthGuard } from "../guards/jwt-auth.guard";
import { CurrentUser } from "../decorators/current-user.decorator";
import {
  clearAuthCookies,
  REFRESH_TOKEN_COOKIE,
  setAuthCookies,
} from "../utils/auth-cookie";

@ApiTags("Auth · SSO")
@Controller("auth/sso")
export class SsoController {
  constructor(private readonly sso: SsoService) {}

  @Get("status")
  @ApiOperation({ summary: "Whether MCOM Central Hub SSO is enabled" })
  status(): { enabled: boolean } {
    return { enabled: this.sso.isEnabled() };
  }

  @Get("login")
  @ApiOperation({
    summary: "Begin SSO — returns the MCOM Central authorize URL",
  })
  @ApiQuery({ name: "state", description: "CSRF state generated by the client" })
  @ApiQuery({ name: "returnPath", required: false })
  login(
    @Query("state") state: string,
    @Query("returnPath") returnPath?: string,
  ): Promise<{ authorizeUrl: string }> {
    return this.sso.createLogin(state, returnPath ?? "/");
  }

  @Post("callback")
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: "Exchange the authorization code and establish a local session",
  })
  async callback(
    @Body() dto: SsoCallbackDto,
    @Res({ passthrough: true }) res: Response,
  ) {
    const result = await this.sso.handleCallback(dto.code, dto.state);
    if (result.success && result.tokens) {
      setAuthCookies(res, result.tokens.accessToken, result.tokens.refreshToken);
    }
    return result;
  }

  @Post("direct-login")
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: "Flow B — direct dashboard handshake" })
  async directLogin(
    @Body() dto: SsoDirectLoginDto,
    @Res({ passthrough: true }) res: Response,
  ) {
    const result = await this.sso.handleDirectToken(dto.token);
    if (result.success && result.tokens) {
      setAuthCookies(res, result.tokens.accessToken, result.tokens.refreshToken);
    }
    return result;
  }

  @Post("refresh-entitlement")
  @HttpCode(HttpStatus.OK)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: "Re-introspect the current user's entitlement" })
  refreshEntitlement(@CurrentUser("id") userId: string) {
    return this.sso.refreshEntitlement(userId);
  }

  @Post("refresh-profile")
  @HttpCode(HttpStatus.OK)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({
    summary: "Re-read the current user's identity from Central Hub",
  })
  refreshProfile(@CurrentUser("id") userId: string) {
    return this.sso.refreshProfile(userId);
  }

  @Post("logout")
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: "Clear the local session and return the Central SLO URL" })
  async logout(
    @Body() body: { refreshToken?: string },
    @Req() req: Request,
    @Res({ passthrough: true }) res: Response,
  ) {
    const refreshToken = body?.refreshToken || req.cookies?.[REFRESH_TOKEN_COOKIE];
    clearAuthCookies(res);
    return this.sso.logout(refreshToken);
  }
}
